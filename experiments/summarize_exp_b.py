"""Summarise results/exp_b.jsonl -> results/exp_b.csv, results/exp_b_summary.md, figures."""
from __future__ import annotations

import json
import os

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "results")


def load():
    rows = [json.loads(l) for l in open(os.path.join(RES, "exp_b.jsonl"))]
    df = pd.DataFrame(rows).drop(columns=["x"])
    return df


def paired_boot(a, b, n=2000, seed=0):
    """Mean of (a - b) over draws with a 95% bootstrap interval; negative = a better."""
    rng = np.random.RandomState(seed)
    d = np.asarray(a) - np.asarray(b)
    bs = [d[rng.randint(0, len(d), len(d))].mean() for _ in range(n)]
    return d.mean(), np.percentile(bs, 2.5), np.percentile(bs, 97.5)


def md(t):
    cols = list(t.columns)
    return "\n".join(["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"] +
                     ["| " + " | ".join(str(v) for v in r) + " |" for r in t.values.tolist()])


def main():
    df = load()
    df.to_csv(os.path.join(RES, "exp_b.csv"), index=False)
    out = ["# Experiment B summary (generated by experiments/summarize_exp_b.py)", "",
           "Regret = f(x_hat; theta_true) - f(x*_true; theta_true); mean over 200 draws. `vs nominal` is the paired difference "
           "(method - nominal) with a 95% bootstrap interval; negative means the method beats nominal. See PROTOCOL_B.md.", ""]
    for market, gm in df.groupby("market"):
        out += [f"## {market}", ""]
        rows = []
        for rho, g in gm.groupby("rho"):
            nom = g[g.method == "nominal"].sort_values("draw")
            for method, h in g.groupby("method", sort=False):
                h = h.sort_values("draw")
                md_, lo, hi = paired_boot(h["regret"], nom["regret"])
                rows.append({"rho": rho, "method": method, "delta": f"{h['delta'].mean():.3f}",
                             "mean regret": f"{h['regret'].mean():.2e}", "median regret": f"{h['regret'].median():.2e}",
                             "vs nominal": f"{md_:+.1e} [{lo:+.1e}, {hi:+.1e}]",
                             "dist to x*": f"{h['dist'].mean():.3f}", "eff. N": f"{h['neff'].mean():.2f}",
                             "worst-case excess": f"{(h['worst'] - h['true_val']).mean():.2e}"})
        t = pd.DataFrame(rows)
        out += [md(t), ""]
        chk = gm[gm["sdp_certified"].notna()]
        if len(chk):
            out += [f"SDP check of local result (order 2, {len(chk)} solves, to solver accuracy): certified global in "
                    f"{100 * chk['sdp_certified'].mean():.0f}% for the nominal problem, "
                    f"{100 * chk[chk.method != 'nominal']['sdp_certified'].mean():.0f}% for robust problems "
                    "(uncertified robust cases reflect the relaxation gap ||E z|| <= E||z||, not necessarily local failure).", ""]
    open(os.path.join(RES, "exp_b_summary.md"), "w").write("\n".join(out))
    # figure: mean regret relative to nominal vs delta/||theta||, per rho
    os.makedirs(os.path.join(RES, "figures"), exist_ok=True)
    for market, gm in df.groupby("market"):
        fig, axes = plt.subplots(1, 4, figsize=(13, 3.0), sharey=False)
        for ax, (rho, g) in zip(axes, gm.groupby("rho")):
            nom = g[g.method == "nominal"]["regret"].mean()
            rb = g[g.method.str.startswith("robust")].groupby("delta")["regret"].mean()
            ax.plot(rb.index, rb.values, "o-", color="#0072B2", label="robust (fixed delta)")
            ax.axhline(nom, color="#666666", ls="--", label="nominal")
            for c, col in [(1, "#D55E00"), (2, "#E69F00")]:
                h = g[g.method == f"rule_c{c}"]
                ax.plot(h["delta"].mean(), h["regret"].mean(), "D", color=col, label=f"rule c={c}")
            sh = g[g.method.str.startswith("shrink")].groupby("method")["regret"].mean()
            ax.axhline(sh.min(), color="#009E73", ls=":", label="best shrinkage")
            ax.set_title(f"rho = {rho}", fontsize=9); ax.set_xlabel("delta"); ax.set_xscale("log"); ax.set_yscale("log", nonpositive="clip")
            ax.spines[["top", "right"]].set_visible(False)
        axes[0].set_ylabel("mean true regret"); axes[-1].legend(fontsize=6, frameon=False)
        fig.suptitle(market, fontsize=9); fig.tight_layout()
        fig.savefig(os.path.join(RES, f"figures/exp_b_regret_{market}.png"), dpi=150); plt.close(fig)
    print("\n".join(out)[:3000])


if __name__ == "__main__":
    main()
