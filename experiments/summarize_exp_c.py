"""Experiment C, step 2: out-of-sample metrics and tests from results/exp_c_alloc.jsonl.

Writes results/exp_c_metrics.csv, results/exp_c_tests.csv, results/exp_c_model.csv, results/exp_c_summary.md and figures.
"""
from __future__ import annotations

import itertools
import json
import os

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from sos_portfolio import empirical as em

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "results")
COSTS = (5e-4, 10e-4)
U10 = ["AAPL", "MSFT", "JNJ", "PFE", "JPM", "BAC", "PG", "KO", "HD", "MCD"]


def md(t):
    cols = list(t.columns)
    return "\n".join(["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"] +
                     ["| " + " | ".join(str(v) for v in r) + " |" for r in t.values.tolist()])


def simulate(W, idx, R, cost):
    """W: (n_rebal, n) target weights at rebalance rows idx (sorted); R: simple returns (T, n). Returns gross, net, turnover."""
    gross, net, turn = [], [], []
    w_prev = None
    bounds = list(idx) + [R.shape[0]]
    for k in range(len(idx)):
        w = W[k].copy()
        tv = 0.0 if w_prev is None else float(np.abs(w - w_prev).sum())
        turn.append(tv)
        for t in range(bounds[k], bounds[k + 1]):
            g = float(w @ R[t])
            gross.append(g)
            net.append(g - (cost * tv if t == bounds[k] else 0.0))
            w = w * (1 + R[t]) / (1 + g)
        w_prev = w
    return np.array(gross), np.array(net), np.array(turn)


def main():
    rows = [json.loads(l) for l in open(os.path.join(RES, "exp_c_alloc.jsonl"))]
    rows.sort(key=lambda r: r["i"])
    idx = [r["i"] for r in rows]
    px = pd.read_parquet(os.path.join(ROOT, "data/raw/prices.parquet"))
    rets = np.log(px).diff().dropna()
    R_all = np.expm1(rets.values)
    cols = list(rets.columns)
    out_lines = ["# Experiment C summary (generated by experiments/summarize_exp_c.py)", "",
                 f"Rebalances: {len(rows)} ({rows[0]['date']} .. {rows[-1]['date']}); evaluation window ends {rets.index[-1].date()}. "
                 "Protocol: experiments/PROTOCOL_C.md. Universe is fixed ex post (survivorship bias); costs are one-way bps on traded notional.", ""]
    metrics, series, tests, model = [], {}, [], []
    for U in ("U10", "U37"):
        tickers = U10 if U == "U10" else cols
        ix = [cols.index(t) for t in tickers]
        R = R_all[:, ix]
        names = [k for k in rows[0][U] if "w" in rows[0][U][k]]
        for name in names:
            W = np.array([r[U][name]["w"] for r in rows])
            res = {}
            for c in COSTS:
                g, n_, tv = simulate(W, idx, R[:, :], c)
                res[c] = (g, n_, tv)
            g, n5, tv = res[COSTS[0]]
            _, n10, _ = res[COSTS[1]]
            start = idx[0]
            series[(U, name)] = (g, n5, n10)
            p5 = em.performance(n5, g)
            row = {"universe": U, "strategy": name, **{k: v for k, v in p5.items() if k in ("ann_vol", "cvar5", "max_drawdown", "skew")},
                   "turnover": float(np.mean(tv[1:])), "eff_N": float(np.mean(1 / (W ** 2).sum(axis=1))),
                   "net_ret_5bp": float(n5.mean() * 252), "net_ret_10bp": float(n10.mean() * 252),
                   "sharpe_5bp": p5["sharpe_net"], "time_per_rebal_s": float(np.mean([r[U][name].get("time", np.nan) for r in rows]))}
            if "SOS" in name:
                row["certified"] = float(np.mean([r[U][name].get("certified", False) for r in rows]))
                gaps = [r[U][name].get("gap") for r in rows if r[U][name].get("gap") is not None]
                row["median_gap"] = float(np.median(gaps)) if gaps else np.nan
                row["fallback"] = float(np.mean([r[U][name].get("fallback", False) for r in rows]))
            metrics.append(row)
        # model-level comparison SOS vs local on the estimated polynomial
        for n in names:
            if "_SOS_" in n:
                loc = n.replace("_SOS_", "_local_")
                ol = np.array([r[U][loc]["obj"] for r in rows])
                os_ = np.array([r[U][n]["obj"] for r in rows])
                scale = np.maximum(np.abs(os_), 1e-3)
                lbs = np.array([r[U][n].get("lb", np.nan) for r in rows], dtype=float)
                ex = (lbs - os_) / np.maximum(1.0, np.abs(os_))   # > 0: the bound exceeds the objective at the SOS point (solver accuracy)
                model.append({"universe": U, "model": n.replace("_SOS", ""), "frac_local_suboptimal(>1e-4 rel)": float(np.mean((ol - os_) / scale > 1e-4)),
                              "median_rel_excess_local": float(np.median((ol - os_) / scale)),
                              "max_rel_excess_local": float(np.max((ol - os_) / scale)),
                              "frac_certified": float(np.mean([r[U][n].get("certified", False) for r in rows])),
                              "lb_excess_median": float(np.median(ex)), "lb_excess_max": float(np.max(ex)),
                              "frac_lb_excess_le_1e-5": float(np.mean(ex <= 1e-5))})
    # price of sparsity
    sp = []
    for w4 in (0.0, 1.0, 3.0):
        a = np.array([r["U37"][f"fullmodel_obj_at_sector_SOS_w4={w4:g}"]["obj"] for r in rows])
        b = np.array([r["U37"][f"fullmodel_obj_at_full_local_w4={w4:g}"]["obj"] for r in rows])
        c_ = np.array([r["U37"][f"fullmodel_obj_at_sector_local_w4={w4:g}"]["obj"] for r in rows])
        sp.append({"w4": w4, "full-model F at sector-SOS (mean)": f"{a.mean():.3f}", "full-model F at full-local (mean)": f"{b.mean():.3f}",
                   "rel. loss sector-SOS vs full-local (median)": f"{np.median((a - b) / np.maximum(np.abs(b), 1e-3)):.3f}",
                   "frac dates sector-SOS worse": f"{np.mean(a > b + 1e-9):.2f}"})
    M = pd.DataFrame(metrics)
    M.to_csv(os.path.join(RES, "exp_c_metrics.csv"), index=False)
    pd.DataFrame(model).to_csv(os.path.join(RES, "exp_c_model.csv"), index=False)
    # inference: every pair (primary SOS model vs each other strategy), listed in full
    for U in ("U10", "U37"):
        prim = "Poly_full_SOS_w4=1" if U == "U10" else "Poly_sector_SOS_w4=1"
        for other in [n for (u, n) in series if u == U and n != prim and (n in ("EW", "MinVar_LW", "ERC_LW", "HRP", "MinCVaR95") or
                                                                        n.startswith("Poly_") and "w4=1" in n)]:
            ga, na, _ = series[(U, prim)]
            gb, nb, _ = series[(U, other)]
            vol = em.block_bootstrap_diff(ga, gb, lambda x: x.std(ddof=1) * np.sqrt(252))
            cv = em.block_bootstrap_diff(ga, gb, lambda x: -x[x <= np.quantile(x, 0.05)].mean())
            nr = em.block_bootstrap_diff(na, nb, lambda x: x.mean() * 252)
            sh = em.sharpe_diff_test(na, nb)
            tests.append({"universe": U, "A": prim, "B": other, "d_vol": vol[0], "vol_lo": vol[1], "vol_hi": vol[2],
                          "d_cvar5": cv[0], "cvar_lo": cv[1], "cvar_hi": cv[2], "d_netret": nr[0], "netret_lo": nr[1],
                          "netret_hi": nr[2], "sharpe_p": sh["p_value"]})
    T = pd.DataFrame(tests)
    T.to_csv(os.path.join(RES, "exp_c_tests.csv"), index=False)
    fmt = {"ann_vol": "{:.3f}", "cvar5": "{:.4f}", "max_drawdown": "{:.3f}", "skew": "{:.2f}", "turnover": "{:.3f}", "eff_N": "{:.1f}",
           "net_ret_5bp": "{:.3f}", "net_ret_10bp": "{:.3f}", "sharpe_5bp": "{:.2f}", "time_per_rebal_s": "{:.2f}",
           "certified": "{:.2f}", "median_gap": "{:.1e}", "fallback": "{:.2f}"}
    for U in ("U10", "U37"):
        t = M[M.universe == U].drop(columns="universe").copy()
        for c, f in fmt.items():
            if c in t:
                t[c] = t[c].map(lambda v: "" if pd.isna(v) else f.format(v))
        out_lines += [f"## Out-of-sample metrics, {U} ({'10 assets, full co-moment model' if U == 'U10' else '37 assets, 9 sectors'})", "",
                      "Volatility, net return annualised; CVaR 5% daily; turnover = mean one-way turnover per rebalance; Sharpe net of 5 bp (secondary).", "", md(t), ""]
    out_lines += ["## SOS versus multi-start local on the estimated polynomial (model objective)", "", md(pd.DataFrame(model).round(6).assign(**{c: pd.DataFrame(model)[c].map("{:.1e}".format) for c in ("lb_excess_median", "lb_excess_max")})), "",
                  "## Price of sparsity (37 assets): full co-moment model evaluated at the sector-model solution", "", md(pd.DataFrame(sp)), "",
                  f"## Tests: {len(T)} pairwise comparisons, all reported; no multiple-comparison correction; intervals are 95% circular-block bootstrap (21 days), Sharpe p-values from the Ledoit-Wolf (2008) studentised bootstrap.", "",
                  md(T.round(5)), ""]
    open(os.path.join(RES, "exp_c_summary.md"), "w").write("\n".join(out_lines))
    # cumulative-return figure
    os.makedirs(os.path.join(RES, "figures"), exist_ok=True)
    fig, axes = plt.subplots(1, 2, figsize=(11, 3.4))
    dates = rets.index[idx[0]:]
    for ax, U in zip(axes, ("U10", "U37")):
        for (u, n), (g, n5, n10) in series.items():
            if u == U and (n in ("EW", "MinVar_LW", "HRP") or (n.endswith("w4=1") and ("SOS" in n or "full_local" in n))):
                ax.plot(dates[: len(n5)], np.cumsum(n5), lw=1, label=n)
        ax.set_title(U, fontsize=9); ax.legend(fontsize=6, frameon=False); ax.spines[["top", "right"]].set_visible(False)
        ax.set_ylabel("cumulative log-return (net 5 bp)")
    fig.tight_layout(); fig.savefig(os.path.join(RES, "figures/exp_c_cumulative.png"), dpi=150); plt.close(fig)
    print("\n".join(out_lines)[:4000])


if __name__ == "__main__":
    main()
